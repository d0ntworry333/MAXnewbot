def _deficit_intro(week: int) -> str:
    label = "🥗 Дефицит калорий · недели 1–2" if week <= 2 else f"🥗 Дефицит калорий"
    return _with_week(week, f"{label}\n\n{_DEFICIT_INTRO_BODY}")


def _surplus_intro(week: int) -> str:
    label = "💪 Профицит калорий · недели 1–2" if week <= 2 else "💪 Профицит калорий"
