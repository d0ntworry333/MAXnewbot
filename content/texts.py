def _get_section(goal: str, week_number: int, section: str) -> str:
    g = _normalize_goal(goal)
    week = clamp_week(week_number)
    if week_has_full_content(week):
        return _FULL_WEEK_TEXTS[g][week][section]
    titles = {
        "intro": "Цель и рацион",
        "activity": "Активность",
        "diet": "План питания",
        "recovery": "Восстановление",
        "training_rules": "Правила тренировок",
    }
    return stub_text(titles.get(section, section), g, week)


