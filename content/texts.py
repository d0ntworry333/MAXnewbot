def _normalize_goal(goal: str | None) -> str:
    if goal in ("дефицит", "профицит"):
        return goal
    return DEFAULT_GOAL


def _with_week(week: int, body: str) -> str:
    """Добавить заголовок недели; убрать дубли «недели 1–2» из первой строки."""
    w = clamp_week(week)
    first_line = body.split("\n", 1)[0]
    if "недели 1–2" in first_line or "недели 1-2" in first_line:
        rest = body.split("\n", 1)[1] if "\n" in body else ""
        body = f"{week_header(w)}\n\n{rest}" if rest else week_header(w)
    elif not body.startswith("📅"):
        body = f"{week_header(w)}\n\n{body}"
    return body


