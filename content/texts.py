def format_useful_bmr(calories: float) -> str:
    """Строка с рассчитанной суточной нормой для раздела питания."""
    return f"🔥 Ваш полезный БМР: {calories:.0f} ккал"


def _inject_useful_bmr(diet_text: str, calories: float | None) -> str:
    if calories is None:
        return diet_text
    bmr_line = format_useful_bmr(calories)
    lines = diet_text.split("\n", 1)
    if lines and lines[0].startswith("📊 План питания"):
        body = lines[1].lstrip("\n") if len(lines) > 1 else ""
        return f"{lines[0]}\n\n{bmr_line}\n\n{body}"
    return f"{bmr_line}\n\n{diet_text}"


def get_diet_text(goal: str, week_number: int = 1, calories: float | None = None) -> str:
    return _inject_useful_bmr(_get_section(goal, week_number, "diet"), calories)


def get_activity_text(goal: str, week_number: int = 1) -> str:
    return _get_section(goal, week_number, "activity")


def get_recovery_text(goal: str, week_number: int = 1) -> str:
    return _get_section(goal, week_number, "recovery")


def get_training_rules_text(goal: str, week_number: int = 1) -> str:
    return _get_section(goal, week_number, "training_rules")


def get_nutrition_text(goal: str, week_number: int = 1, calories: float | None = None) -> str:
    """Вводный блок + активность + план питания для раздела «Цель и рацион»."""
    week = clamp_week(week_number)
    return "\n\n".join([
        _get_section(goal, week, "intro"),
        _get_section(goal, week, "activity"),
        get_diet_text(goal, week, calories),
    ])
