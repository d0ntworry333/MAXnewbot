def _training_rules_for_week(goal: str, week: int) -> str:
    w = clamp_week(week)
    if goal == "дефицит":
        body = _DEFICIT_TRAINING_RULES_W2 if w == 2 else _DEFICIT_TRAINING_RULES_W1
    else:
        body = _SURPLUS_TRAINING_RULES_W2 if w == 2 else _SURPLUS_TRAINING_RULES_W1
    return _with_week(w, body)


