"""Сборка ТЗ по шаблону «проект на двоих исполнителей»."""
from pathlib import Path

from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

OUT = Path(__file__).parent / "TZ_MAXBOT_DVOE.docx"
OUT_DL = Path.home() / "Downloads" / "Техническое задание — Твой тренер (по шаблону).docx"


def _font(run, size=14, bold=False):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = bold
    r = run._element.rPr
    if r is not None:
        r.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def _p(doc, text, *, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, indent=True, size=14):
    para = doc.add_paragraph()
    run = para.add_run(text)
    _font(run, size=size, bold=bold)
    para.alignment = align
    if indent:
        para.paragraph_format.first_line_indent = Cm(1.25)
    para.paragraph_format.line_spacing = 1.5
    return para


