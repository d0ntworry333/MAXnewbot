def _set_run_font(run, name: str = "Times New Roman", size: int = 14, bold: bool = False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    r = run._element.rPr
    if r is not None:
        r.rFonts.set(qn("w:eastAsia"), name)


def _para(
    doc: Document,
    text: str,
    *,
    bold: bool = False,
    align=WD_ALIGN_PARAGRAPH.JUSTIFY,
    indent: bool = True,
    size: int = 14,
    spacing: float = 1.5,
    space_after: int = 0,
):
    p = doc.add_paragraph()
    run = p.add_run(text)
    _set_run_font(run, size=size, bold=bold)
    p.alignment = align
    p.paragraph_format.line_spacing = spacing
    p.paragraph_format.space_after = Pt(space_after)
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    return p


def _heading(doc: Document, text: str, level: int = 1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        _set_run_font(run, size=14 if level > 1 else 14, bold=True)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)
    return p


def _bullet(doc: Document, items: list[str]):
    for item in items:
        p = doc.add_paragraph(item, style="List Bullet")
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.left_indent = Cm(1.25)
        for run in p.runs:
            _set_run_font(run)


def _numbered(doc: Document, items: list[str]):
    for i, item in enumerate(items, 1):
        _para(doc, f"{i}. {item}")


def _figure(doc: Document, path: Path, caption: str, width_in: float = 5.5):
    if not path.is_file():
        _para(doc, f"[{caption} — файл не найден: {path.name}]", indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(path), width=Inches(width_in))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(caption)
    _set_run_font(r, size=12)
    cap.paragraph_format.line_spacing = 1.0
    cap.paragraph_format.space_after = Pt(12)


def _table(doc: Document, headers: list[str], rows: list[list[str]], caption: str):
    _para(doc, caption, bold=True, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = h
        for p in cell.paragraphs:
            for run in p.runs:
                _set_run_font(run, size=12, bold=True)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.rows[ri + 1].cells[ci]
            cell.text = str(val)
            for p in cell.paragraphs:
                for run in p.runs:
                    _set_run_font(run, size=12)
    doc.add_paragraph()


def _setup_page(doc: Document):
    section = doc.sections[0]
    for margin in (section.top_margin, section.bottom_margin, section.left_margin, section.right_margin):
        pass
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(2)
    section.right_margin = Cm(2)
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)


